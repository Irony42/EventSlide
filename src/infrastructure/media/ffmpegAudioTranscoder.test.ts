/**
 * Ring 3: the real encoder on real recordings, as a browser or a phone would produce them.
 *
 * The fixtures are **generated by ffmpeg itself** (see `ffmpegVideoTranscoder.test.ts` for why a
 * committed binary is the worse trade), one flag away from each shape that matters:
 *
 * - **WebM/Opus with no duration**, `-live 1`: what Chrome's `MediaRecorder` writes;
 * - **Ogg/Opus**: desktop Firefox;
 * - **MP4/AAC with the `M4A ` brand, tags and a GPS position**: the stand-in for an iPhone. A real
 *   recording from a phone is a fixture only a person with a phone can make; this one carries the
 *   `ftyp` mark and the tags Apple writes, and the sample a tester captures is to be added beside it;
 * - **a fragmented MP4**, the shape Safari's `MediaRecorder` produces;
 * - a disguised video, a container truncated before its `moov`, a header that lies.
 */

const MACHINE_PATH = process.env['PATH'] ?? ''
const MACHINE_PATHEXT = process.env['PATHEXT'] ?? ''
const SEARCH = { path: MACHINE_PATH, extensions: MACHINE_PATHEXT }
const MACHINE_ENV = minimalChildEnv({
  path: MACHINE_PATH,
  pathExt: MACHINE_PATHEXT,
  systemRoot: process.env['SYSTEMROOT'] ?? '',
  winDir: process.env['WINDIR'] ?? '',
  temp: process.env['TEMP'] ?? '',
  tmp: process.env['TMP'] ?? '',
})

/** Written into the source's tags, so the output can be searched for them. */
const SECRET_TITLE = 'SECRETVOICETITLE'
const SECRET_POSITION = '+48.8566+002.3522/'

interface Harness {
  readonly paths: FfmpegPaths
  readonly scratch: string
  readonly work: string
  readonly transcoder: FfmpegAudioTranscoder
  readonly fixtures: VoiceFixtures
  readonly extra: {
    readonly webm: Uint8Array
    readonly ogg: Uint8Array
    readonly iphone: Uint8Array
    readonly fragmented: Uint8Array
    readonly lying: Uint8Array
    readonly tenSeconds: Uint8Array
  }
}

let harness: Harness

const requireFfmpeg = async (): Promise<FfmpegPaths> => {
  const capability = await probeFfmpegCapability({ search: SEARCH, env: MACHINE_ENV })
  if (!capability.available) {
    throw new Error(
      `this ring-3 suite needs a working ffmpeg: ${capability.reason}. ` +
        `Install one, or run \`npm ci\` so the ffmpeg-static devDependency is present.`,
    )
  }
  return capability.paths
}

const generate = async (
  paths: FfmpegPaths,
  directory: string,
  name: string,
  args: readonly string[],
): Promise<Uint8Array> => {
  const file = join(directory, name)
  const result = await runProcess({
    binary: paths.ffmpeg,
    args: ['-nostdin', '-hide_banner', '-loglevel', 'error', '-y', ...args, file],
    env: MACHINE_ENV,
    timeoutMs: 60_000,
    stallMs: 30_000,
  })
  if (!result.ok) throw new Error(`could not generate ${name}: ${result.stderr}`)
  return new Uint8Array(await readFile(file))
}

const sine = (seconds: number): string[] => [
  '-f',
  'lavfi',
  '-i',
  `sine=frequency=440:duration=${seconds}`,
]

/**
 * Opus, by `libopus` where the build has it and by ffmpeg's own encoder otherwise: the native one
 * is marked experimental and needs `-strict -2`, and either produces what a browser would.
 */
const opusOut = async (
  paths: FfmpegPaths,
  directory: string,
  name: string,
  format: string,
  extra: readonly string[],
  seconds: number,
): Promise<Uint8Array> => {
  try {
    return await generate(paths, directory, name, [
      ...sine(seconds),
      '-c:a',
      'libopus',
      ...extra,
      '-f',
      format,
    ])
  } catch {
    return generate(paths, directory, name, [
      ...sine(seconds),
      '-c:a',
      'opus',
      '-strict',
      '-2',
      ...extra,
      '-f',
      format,
    ])
  }
}

/** What ffprobe says a file really holds: its streams and every tag, on the format and the streams. */
const factsOf = async (
  paths: FfmpegPaths,
  directory: string,
  bytes: Uint8Array,
): Promise<{
  streams: Record<string, unknown>[]
  tags: Record<string, string>
  durationSeconds: number
}> => {
  const file = join(directory, `inspect-${Math.random().toString(16).slice(2)}.m4a`)
  await writeFile(file, bytes)
  const result = await runProcess({
    binary: paths.ffprobe,
    args: [
      '-hide_banner',
      '-loglevel',
      'error',
      '-print_format',
      'json',
      '-show_format',
      '-show_streams',
      `file:${file}`,
    ],
    env: MACHINE_ENV,
    timeoutMs: 30_000,
    stallMs: 30_000,
  })
  if (!result.ok) throw new Error(`could not inspect the output: ${result.stderr}`)
  const parsed = JSON.parse(result.stdout) as {
    streams?: Record<string, unknown>[]
    format?: { tags?: Record<string, string>; duration?: string }
  }
  const streams = parsed.streams ?? []
  const tags: Record<string, string> = { ...(parsed.format?.tags ?? {}) }
  for (const stream of streams) {
    Object.assign(tags, (stream['tags'] as Record<string, string> | undefined) ?? {})
  }
  return { streams, tags, durationSeconds: Number(parsed.format?.duration ?? 'NaN') }
}

const contains = (haystack: Uint8Array, needle: string): boolean =>
  Buffer.from(haystack).includes(Buffer.from(needle))

beforeAll(async () => {
  const paths = await requireFfmpeg()
  const scratch = await mkdtemp(join(tmpdir(), 'eventslide-voice-'))

  const webm = await opusOut(paths, scratch, 'live.webm', 'webm', ['-live', '1'], 1.5)
  const ogg = await opusOut(paths, scratch, 'opus.ogg', 'ogg', [], 1.5)

  // An iPhone's voice memo in spirit: AAC at 44.1 kHz mono, `M4A ` as the brand (what the `ipod`
  // muxer writes for audio alone), a title and a GPS position in the metadata.
  const iphone = await generate(paths, scratch, 'iphone.m4a', [
    ...sine(1.5),
    '-ar',
    '44100',
    '-ac',
    '1',
    '-c:a',
    'aac',
    '-b:a',
    '64k',
    '-metadata',
    `title=${SECRET_TITLE}`,
    '-metadata',
    `location=${SECRET_POSITION}`,
    '-f',
    'ipod',
  ])

  // Fragmented, with an empty `moov`: how Safari's `MediaRecorder` writes an MP4.
  const fragmented = await generate(paths, scratch, 'frag.mp4', [
    ...sine(3),
    '-c:a',
    'aac',
    '-movflags',
    'frag_keyframe+empty_moov+default_base_moof',
    '-f',
    'mp4',
  ])

  // Ten seconds with its `moov` in front, cut after 30 kB: the header says ten, the sound is three.
  const tenSeconds = await generate(paths, scratch, 'ten.m4a', [
    ...sine(10),
    '-c:a',
    'aac',
    '-movflags',
    '+faststart',
    '-f',
    'ipod',
  ])
  const lying = tenSeconds.slice(0, 30_000)

  const video = await generate(paths, scratch, 'video.mp4', [
    '-f',
    'lavfi',
    '-i',
    'testsrc2=size=160x120:rate=10:duration=1.5',
    ...sine(1.5),
    '-c:v',
    'libx264',
    '-preset',
    'ultrafast',
    '-pix_fmt',
    'yuv420p',
    '-c:a',
    'aac',
    '-shortest',
    '-f',
    'mp4',
  ])

  // A container with a subtitle track and nothing to hear.
  await writeFile(join(scratch, 'caption.srt'), '1\n00:00:00,000 --> 00:00:01,000\nhi\n')
  const silentContainer = await generate(paths, scratch, 'silent.mp4', [
    '-f',
    'srt',
    '-i',
    join(scratch, 'caption.srt'),
    '-c:s',
    'mov_text',
    '-f',
    'mp4',
  ])

  const mp4 = await generate(paths, scratch, 'spoken.m4a', [...sine(1.5), '-c:a', 'aac', '-f', 'ipod'])

  const fixtures: VoiceFixtures = {
    spoken: mp4,
    noDuration: webm,
    long: await generate(paths, scratch, 'long.m4a', [...sine(6), '-c:a', 'aac', '-f', 'ipod']),
    lyingHeader: lying,
    tap: await generate(paths, scratch, 'tap.m4a', [...sine(0.3), '-c:a', 'aac', '-f', 'ipod']),
    video,
    silentContainer,
    notAVoice: new TextEncoder().encode('%PDF-1.7\nthis is not a recording at all\n'),
    // The `ftyp` is there and the `moov` is not: a phone that died mid-recording. Not faststart,
    // so the `moov` is at the end and a cut at 1 kB leaves none.
    corrupt: mp4.slice(0, 1_024),
  }

  const work = join(scratch, 'work')
  harness = {
    paths,
    scratch,
    work,
    transcoder: createFfmpegAudioTranscoder({ paths, scratchRoot: work, env: MACHINE_ENV }),
    fixtures,
    extra: { webm, ogg, iphone, fragmented, lying, tenSeconds },
  }
}, 180_000)

afterAll(async () => {
  harness?.transcoder.close()
  if (harness !== undefined) await rm(harness.scratch, { recursive: true, force: true })
})

audioTranscoderContract('ffmpeg', async () => ({
  transcoder: harness.transcoder,
  fixtures: harness.fixtures,
}))

const scratchEntries = async (): Promise<string[]> =>
  readdir(harness.work).catch(() => [] as string[])

describe('buildVoiceEncodeArgs', () => {
  const args = buildVoiceEncodeArgs({
    ffmpegInput: '/scratch/in.bin',
    output: '/scratch/out.m4a',
    container: 'matroska',
    spec: { maxDurationMs: 60_000, minDurationMs: 1_000, maxOutputBytes: 1_000_000 },
  })

  const at = (flag: string): number => args.indexOf(flag)

  it('allows no protocol but the local file, on the encoder as on the header read', () => {
    expect(args.slice(at('-protocol_whitelist'), at('-protocol_whitelist') + 2)).toEqual([
      '-protocol_whitelist',
      'file',
    ])
    const probe = buildVoiceProbeArgs('/scratch/in.bin', 'ogg')
    expect(probe.slice(probe.indexOf('-protocol_whitelist'), probe.indexOf('-protocol_whitelist') + 2)).toEqual(
      ['-protocol_whitelist', 'file'],
    )
  })

  it('addresses both files as file: paths and pins the demuxer the signature chose', () => {
    expect(args).toContain('file:/scratch/in.bin')
    expect(args).toContain('file:/scratch/out.m4a')
    expect(args[at('-f') + 1]).toBe('matroska,webm')
    const probe = buildVoiceProbeArgs('/scratch/in.bin', 'ogg')
    expect(probe[probe.indexOf('-f') + 1]).toBe('ogg')
    expect(probe).toContain('file:/scratch/in.bin')
  })

  it('puts the bounds on the input scan before -i, where they are input options', () => {
    expect(at('-probesize')).toBeGreaterThan(-1)
    expect(at('-probesize')).toBeLessThan(at('-i'))
    expect(at('-analyzeduration')).toBeGreaterThan(-1)
    expect(at('-analyzeduration')).toBeLessThan(at('-i'))
    const probe = buildVoiceProbeArgs('/scratch/in.bin', 'mp4')
    expect(probe.indexOf('-probesize')).toBeGreaterThan(-1)
    expect(probe.indexOf('-probesize')).toBeLessThan(probe.findIndex((a) => a.startsWith('file:')))
  })

  it('re-encodes, never copies, and strips every stream and tag that is not the sound', () => {
    expect(args).not.toContain('copy')
    for (const flag of ['-vn', '-dn', '-sn']) expect(args).toContain(flag)
    expect(args.slice(at('-map_metadata'), at('-map_metadata') + 2)).toEqual(['-map_metadata', '-1'])
    expect(args.slice(at('-map_chapters'), at('-map_chapters') + 2)).toEqual(['-map_chapters', '-1'])
    expect(args.slice(at('-map'), at('-map') + 2)).toEqual(['-map', '0:a:0'])
  })

  it('bounds the output by duration and by size, whatever the header claimed', () => {
    expect(args[at('-t') + 1]).toBe('60.000')
    expect(args[at('-fs') + 1]).toBe('1000000')
  })

  it('writes mono AAC at a voice bitrate into an MP4 whose index comes first', () => {
    expect(args.slice(at('-ac'), at('-ac') + 2)).toEqual(['-ac', '1'])
    expect(args.slice(at('-c:a'), at('-c:a') + 2)).toEqual(['-c:a', 'aac'])
    expect(args.slice(at('-b:a'), at('-b:a') + 2)).toEqual(['-b:a', '48k'])
    expect(args.slice(at('-movflags'), at('-movflags') + 2)).toEqual(['-movflags', '+faststart'])
  })
})

describe('ffmpegAudioTranscoder against real recordings', () => {
  const spec = { maxDurationMs: 60_000, minDurationMs: 1_000, maxOutputBytes: 1_000_000 }

  it.each([
    ['WebM/Opus with no duration (Chrome)', 'webm', 'matroska'],
    ['Ogg/Opus (desktop Firefox)', 'ogg', 'ogg'],
    ['MP4/AAC with the M4A brand (an iPhone)', 'iphone', 'mp4'],
    ['a fragmented MP4 (Safari MediaRecorder)', 'fragmented', 'mp4'],
  ] as const)('turns %s into mono AAC in an MP4', async (_name, key, container) => {
    const source = harness.extra[key]
    expect(harness.transcoder.identify(source)).toBe(container)

    const result = await harness.transcoder.transcode(source, spec)

    expect(result.ok).toBe(true)
    if (!result.ok) return
    const facts = await factsOf(harness.paths, harness.scratch, result.value.bytes)
    expect(facts.streams.map((stream) => stream['codec_type'])).toEqual(['audio'])
    expect(facts.streams[0]).toMatchObject({ codec_name: 'aac', channels: 1, sample_rate: '32000' })
    // The container is an MP4 a browser plays.
    expect(Buffer.from(result.value.bytes.slice(4, 8)).toString('ascii')).toBe('ftyp')
    // Measured on the output: about what was recorded, to a frame of AAC priming either way.
    expect(Math.abs(result.value.durationMs - facts.durationSeconds * 1000)).toBeLessThan(5)
    expect(result.value.durationMs).toBeGreaterThan(1_300)
  })

  it('keeps the cost of a voice near 6 kB a second, so a minute stays under the output ceiling', async () => {
    const result = await harness.transcoder.transcode(harness.extra.tenSeconds, spec)

    expect(result.ok).toBe(true)
    if (!result.ok) return
    expect(result.value.byteSize / (result.value.durationMs / 1000)).toBeLessThan(9_000)
  })

  it('carries no tag, position or title of the source into the output', async () => {
    const result = await harness.transcoder.transcode(harness.extra.iphone, spec)

    expect(result.ok).toBe(true)
    if (!result.ok) return
    expect(contains(harness.extra.iphone, SECRET_TITLE)).toBe(true)
    expect(contains(result.value.bytes, SECRET_TITLE)).toBe(false)
    expect(contains(result.value.bytes, SECRET_POSITION)).toBe(false)
    const facts = await factsOf(harness.paths, harness.scratch, result.value.bytes)
    expect(Object.keys(facts.tags).sort()).not.toContain('title')
    expect(Object.keys(facts.tags).sort()).not.toContain('location')
    expect(Object.values(facts.tags).join(' ')).not.toContain(SECRET_TITLE)
  })

  it('stores the duration it measured on the output, not the ten seconds a truncated header claims', async () => {
    const claimed = await harness.transcoder.probe(harness.extra.lying)
    expect(claimed.ok && claimed.value.durationMs).toBeGreaterThan(9_000)

    const result = await harness.transcoder.transcode(harness.extra.lying, spec)

    expect(result.ok).toBe(true)
    if (!result.ok) return
    expect(result.value.durationMs).toBeLessThan(5_000)
    expect(result.value.durationMs).toBeGreaterThan(1_000)
  })

  it('bounds the output at the cap whatever the header says', async () => {
    const result = await harness.transcoder.transcode(harness.extra.tenSeconds, {
      ...spec,
      maxDurationMs: 3_000,
    })

    expect(result.ok).toBe(true)
    expect(result.ok && result.value.durationMs).toBeLessThanOrEqual(3_100)
  })

  it('answers a fragmented MP4 whose duration is not in its header, with a duration measured on the output', async () => {
    const probed = await harness.transcoder.probe(harness.extra.fragmented)
    expect(probed.ok).toBe(true)

    const result = await harness.transcoder.transcode(harness.extra.fragmented, spec)
    expect(result.ok && result.value.durationMs).toBeGreaterThan(2_500)
  })

  it('refuses an output larger than the ceiling it was given rather than storing half a message', async () => {
    const result = await harness.transcoder.transcode(harness.extra.tenSeconds, {
      ...spec,
      maxOutputBytes: 2_000,
    })

    expect(result.ok).toBe(false)
    expect(!result.ok && result.error.code).toMatch(/^voice\.(transcodeFailed|tooShort)$/)
  })

  it('leaves no scratch file behind, after a success or a refusal of any kind', async () => {
    await harness.transcoder.transcode(harness.extra.webm, spec)
    await harness.transcoder.transcode(harness.fixtures.video, spec)
    await harness.transcoder.transcode(harness.fixtures.corrupt, spec)
    await harness.transcoder.transcode(harness.fixtures.silentContainer, spec)
    await harness.transcoder.probe(harness.fixtures.corrupt)

    expect(await scratchEntries()).toEqual([])
  })

  it('answers a timeout with its own code, kills the child and leaves nothing behind', async () => {
    const impatient = createFfmpegAudioTranscoder({
      paths: harness.paths,
      scratchRoot: harness.work,
      env: MACHINE_ENV,
      timeoutMs: 1,
      stallMs: 1,
    })

    const result = await impatient.transcode(harness.extra.webm, spec)

    expect(!result.ok && result.error.code).toBe('voice.transcodeTimedOut')
    impatient.close()
    expect(await scratchEntries()).toEqual([])
  })

  it('says the box has no encoder when the binary cannot be started', async () => {
    const broken = createFfmpegAudioTranscoder({
      paths: { ffmpeg: join(harness.scratch, 'absent-ffmpeg'), ffprobe: join(harness.scratch, 'absent-ffprobe') },
      scratchRoot: harness.work,
      env: MACHINE_ENV,
    })

    const result = await broken.transcode(harness.extra.webm, spec)

    expect(!result.ok && result.error.code).toBe('voice.transcoderUnavailable')
    expect(await scratchEntries()).toEqual([])
  })

  it('refuses a video renamed as a voice before encoding anything, as notAudio', async () => {
    const result = await harness.transcoder.transcode(harness.fixtures.video, spec)

    expect(!result.ok && result.error.code).toBe('voice.notAudio')
  })

  it('refuses a recording truncated before its index as corrupt, a permanent verdict', async () => {
    const result = await harness.transcoder.transcode(harness.fixtures.corrupt, spec)

    expect(!result.ok && result.error.code).toBe('voice.corrupt')
  })

  it('reports a filesystem that cannot hold the scratch file as a transient storage failure', async () => {
    // The scratch root is a regular file, so the directory cannot be made.
    const blocker = join(harness.scratch, 'not-a-directory')
    await writeFile(blocker, 'x')
    const stuck = createFfmpegAudioTranscoder({
      paths: harness.paths,
      scratchRoot: join(blocker, 'below'),
      env: MACHINE_ENV,
    })

    const result = await stuck.transcode(harness.extra.webm, spec)

    expect(!result.ok && result.error.code).toBe('voice.storageFailed')
  })
})
