import { mkdtemp, readdir, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import sharp from 'sharp'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import {
  REEL_CONTRACT_SPEC,
  reelRendererContract,
} from '../../application/testing/contracts/reelRendererContract'
import { probeFfmpegCapability, type FfmpegPaths } from './ffmpegBinaries'
import { createFfmpegReelRenderer, type FfmpegReelRenderer } from './ffmpegReelRenderer'
import { minimalChildEnv, runProcess } from './runProcess'

/**
 * Ring 3: the real encoder on real pictures (spec 08).
 *
 * The pictures are generated by `sharp`, as the pipeline would have produced a `display`
 * rendition, so nothing here depends on a sample file. What is asserted is what a host and a
 * browser rely on: the size, one video stream and no audio, no metadata that names a machine, a
 * duration that follows the spec, a portrait photograph kept upright and uncropped, and a scratch
 * directory that is gone after a failure.
 */

// A test file, where `no-restricted-syntax` is off.
const MACHINE_PATH = process.env['PATH'] ?? ''
const MACHINE_PATHEXT = process.env['PATHEXT'] ?? ''
const SEARCH = { path: MACHINE_PATH, extensions: MACHINE_PATHEXT }
const MACHINE_ENV = minimalChildEnv({
  path: MACHINE_PATH,
  pathExt: MACHINE_PATHEXT,
  systemRoot: process.env['SYSTEMROOT'] ?? '',
  winDir: process.env['WINDIR'] ?? '',
  temp: process.env['TEMP'] ?? '',
  tmp: process.env['TMP'] ?? '',
})

const SPEC = { secondsPerPhoto: 2, maxOutputBytes: 50_000_000 }

let paths: FfmpegPaths
let workdir: string
let scratchRoot: string
let renderer: FfmpegReelRenderer
let landscape: Uint8Array
let portraitWhite: Uint8Array

const jpeg = async (width: number, height: number, colour: string): Promise<Uint8Array> =>
  new Uint8Array(
    await sharp({ create: { width, height, channels: 3, background: colour } })
      .jpeg()
      .toBuffer(),
  )

const ffprobe = async (file: string): Promise<Record<string, unknown>> => {
  const result = await runProcess({
    binary: paths.ffprobe,
    args: [
      '-hide_banner',
      '-loglevel',
      'error',
      '-print_format',
      'json',
      '-show_format',
      '-show_streams',
      `file:${file}`,
    ],
    env: MACHINE_ENV,
    timeoutMs: 30_000,
    stallMs: 30_000,
  })
  if (!result.ok) throw new Error(`could not inspect the output: ${result.stderr}`)
  return JSON.parse(result.stdout) as Record<string, unknown>
}

const written = async (bytes: Uint8Array): Promise<string> => {
  const file = join(workdir, `out-${Math.random().toString(16).slice(2)}.mp4`)
  await writeFile(file, bytes)
  return file
}

/** One decoded pixel of the frame at `seconds`, as [r, g, b]. */
const pixelAt = async (
  file: string,
  seconds: number,
  x: number,
  y: number,
): Promise<readonly number[]> => {
  const raw = join(workdir, `frame-${Math.random().toString(16).slice(2)}.rgb`)
  const made = await runProcess({
    binary: paths.ffmpeg,
    args: [
      '-nostdin',
      '-hide_banner',
      '-loglevel',
      'error',
      '-y',
      '-ss',
      String(seconds),
      '-i',
      `file:${file}`,
      '-frames:v',
      '1',
      '-f',
      'rawvideo',
      '-pix_fmt',
      'rgb24',
      `file:${raw}`,
    ],
    env: MACHINE_ENV,
    timeoutMs: 30_000,
    stallMs: 30_000,
  })
  if (!made.ok) throw new Error(`could not decode a frame: ${made.stderr}`)
  const { readFile } = await import('node:fs/promises')
  const bytes = await readFile(raw)
  const offset = (y * 1280 + x) * 3
  return [bytes[offset] ?? -1, bytes[offset + 1] ?? -1, bytes[offset + 2] ?? -1]
}

beforeAll(async () => {
  const capability = await probeFfmpegCapability({ search: SEARCH, env: MACHINE_ENV })
  if (!capability.available) {
    throw new Error(
      `this ring-3 suite needs a working ffmpeg: ${capability.reason}. ` +
        `Run \`npm ci\` so the ffmpeg-static devDependency is present.`,
    )
  }
  paths = capability.paths
  workdir = await mkdtemp(join(tmpdir(), 'reel-test-'))
  scratchRoot = join(workdir, '.scratch')
  renderer = createFfmpegReelRenderer({ paths, scratchRoot, env: MACHINE_ENV })
  landscape = await jpeg(640, 360, '#3366cc')
  portraitWhite = await jpeg(360, 640, '#ffffff')
}, 60_000)

afterAll(async () => {
  renderer.close()
  await rm(workdir, { recursive: true, force: true })
})

reelRendererContract('ffmpeg', async () => ({
  renderer,
  frames: [landscape, landscape, landscape],
}))

describe('the file the encoder makes', () => {
  it('is 1280x720 H.264 with one video stream, no audio, and a duration that follows the spec', async () => {
    const made = await renderer.render([landscape, landscape, landscape], SPEC)
    if (!made.ok) throw new Error(made.error.code)

    const probed = await ffprobe(await written(made.value.bytes))

    const streams = probed['streams'] as Record<string, unknown>[]
    expect(streams).toHaveLength(1)
    expect(streams[0]).toMatchObject({
      codec_type: 'video',
      codec_name: 'h264',
      width: 1280,
      height: 720,
      pix_fmt: 'yuv420p',
    })
    const duration = Number((probed['format'] as Record<string, unknown>)['duration'])
    expect(duration).toBeGreaterThan(5.5)
    expect(duration).toBeLessThan(6.5)
  }, 120_000)

  it('carries no metadata that names the evening or the machine', async () => {
    const made = await renderer.render([landscape, landscape, landscape], SPEC)
    if (!made.ok) throw new Error(made.error.code)

    const probed = await ffprobe(await written(made.value.bytes))

    const tags = Object.keys(
      ((probed['format'] as Record<string, unknown>)['tags'] as Record<string, unknown>) ?? {},
    ).filter((key) => !['major_brand', 'minor_version', 'compatible_brands'].includes(key))
    expect(tags).toEqual([])
  }, 120_000)

  it('keeps a portrait photograph upright and uncropped, with bars either side', async () => {
    const made = await renderer.render([portraitWhite, portraitWhite, portraitWhite], SPEC)
    if (!made.ok) throw new Error(made.error.code)
    const file = await written(made.value.bytes)

    // At one second, between the fades: the white picture in the middle, black at both edges.
    const centre = await pixelAt(file, 1, 640, 360)
    const leftBar = await pixelAt(file, 1, 20, 360)
    const rightBar = await pixelAt(file, 1, 1260, 360)
    // Portrait, fitted by height: its width is 720 * 360/640 = 405, so x = 640 +- 202 is picture.
    const justInside = await pixelAt(file, 1, 640 + 190, 360)
    const justOutside = await pixelAt(file, 1, 640 + 230, 360)

    expect(Math.min(...centre)).toBeGreaterThan(200)
    expect(Math.max(...leftBar)).toBeLessThan(40)
    expect(Math.max(...rightBar)).toBeLessThan(40)
    expect(Math.min(...justInside)).toBeGreaterThan(200)
    expect(Math.max(...justOutside)).toBeLessThan(40)
  }, 120_000)
})

describe('when it fails', () => {
  it('leaves no scratch directory behind, and says the render failed', async () => {
    const made = await renderer.render([Uint8Array.of(1, 2, 3), landscape, landscape], SPEC)

    expect(!made.ok && made.error.code).toBe('reel.renderFailed')
    const leftovers = (await readdir(scratchRoot)).filter((name) => name.startsWith('reel-'))
    expect(leftovers).toEqual([])
  }, 120_000)

  it('leaves no scratch directory behind after a success either', async () => {
    await renderer.render([landscape, landscape, landscape], REEL_CONTRACT_SPEC)

    expect((await readdir(scratchRoot)).filter((name) => name.startsWith('reel-'))).toEqual([])
  }, 120_000)

  it('says there is no encoder when the executable cannot be started', async () => {
    const broken = createFfmpegReelRenderer({
      paths: { ffmpeg: join(workdir, 'no-such-ffmpeg'), ffprobe: paths.ffprobe },
      scratchRoot,
      env: MACHINE_ENV,
    })

    const made = await broken.render([landscape, landscape, landscape], SPEC)

    expect(!made.ok && made.error.code).toBe('reel.transcoderUnavailable')
  })

  it('is cancelled, not failed, when the box shuts down mid-render', async () => {
    const pending = renderer.render([landscape, landscape, landscape], SPEC)
    renderer.close()

    const made = await pending

    // Killed before it finished: a retryable cancellation, or a finished file if it won the race.
    expect(made.ok || made.error.code === 'reel.cancelled' || made.error.code === 'reel.renderFailed').toBe(true)
  }, 120_000)

  it('is refused a scratch root it cannot make', async () => {
    const blocked = createFfmpegReelRenderer({
      paths,
      scratchRoot: join(workdir, 'out-0', 'nested'),
      env: MACHINE_ENV,
    })
    // A file stands where a directory is needed.
    await writeFile(join(workdir, 'out-0'), 'x')

    const made = await blocked.render([landscape, landscape, landscape], SPEC)

    expect(!made.ok && made.error.code).toBe('reel.storageFailed')
  })
})
